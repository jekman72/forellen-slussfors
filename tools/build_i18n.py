"""Build i18n/strings.js from i18n/lv.json, lt.json and pl.json.

[[0]], [[1]] ... in a translation are replaced with the 1st, 2nd ... <a> element
of the English source (i18n/en.json), so phone links and URLs always match.
Warns about keys that do not exist in the English source."""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
en = json.load(open(os.path.join(ROOT, 'i18n', 'en.json'), encoding='utf-8'))
out = {}
for lang in ('lv', 'lt', 'pl'):
    d = json.load(open(os.path.join(ROOT, 'i18n', lang + '.json'), encoding='utf-8'))
    res = {}
    for k, v in d.items():
        if not (k.startswith('js.') or k.startswith('meta.') or k.startswith('cal-')) and k not in en:
            print(f'WARN {lang}: unknown key {k}')
        if isinstance(v, str) and '[[' in v:
            anchors = re.findall(r'<a\b[^>]*>.*?</a>', en[k], flags=re.S)
            v = re.sub(r'\[\[(\d+)\]\]', lambda m: anchors[int(m.group(1))], v)
        res[k] = v
    missing = [k for k in en if k not in d and k not in ('forellen', 'slussfors', 'leave-empty', 'gamlav-gen-16-923-97-slussfors-sweden')]
    if missing: print(f'{lang}: {len(missing)} keys fall back to English:', ', '.join(missing))
    out[lang] = res
js = '/* generated by tools/build_i18n.py, edit i18n/lv.json, lt.json and pl.json */\nwindow.I18N = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n'
open(os.path.join(ROOT, 'i18n', 'strings.js'), 'w', encoding='utf-8').write(js)
print('wrote i18n/strings.js', len(js) // 1024, 'kB')
# Cache-bust: point index.html at strings.js?v=<content hash> so browsers never mix old texts with a new page
import hashlib
ver = hashlib.sha1(js.encode('utf-8')).hexdigest()[:8]
ip = os.path.join(ROOT, 'index.html')
html = open(ip, encoding='utf-8').read()
new = re.sub(r'src="i18n/strings\.js(\?v=[0-9a-f]+)?"', 'src="i18n/strings.js?v=' + ver + '"', html)
if new != html:
    open(ip, 'w', encoding='utf-8').write(new)
print('index.html uses strings.js?v=' + ver)
